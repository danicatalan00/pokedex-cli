def single_effectiveness(move_type: str, defender_type: str) -> float:
    """Multiplicador de un tipo atacante contra un único tipo defensor."""
    return _CHART.get(move_type, {}).get(defender_type, 1.0)


def effectiveness(move_type: str, defender_types: Sequence[str]) -> float:
    """Producto de multiplicadores contra cada tipo del defensor (×0 a ×4).

    Un tipo desconocido, en cualquiera de los dos lados, cuenta como neutro:
    datos incompletos nunca deben convertir un ataque en inmune.
    """
    result = 1.0
    for defender_type in defender_types:
        result *= single_effectiveness(move_type, defender_type)
    return result
